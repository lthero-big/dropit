// RHEA-190 m13 preview check: /api/version, 管理 → 更新 (立即检查 against live Docker Hub / GitHub),
// and the new-version notice on 管理 / 设置.
//   ORIGIN=http://152.53.141.33:15199 KEY=$(cat <preview key>) OUT=/tmp node scripts/acceptance-rhea190-m13.mjs
import { createRequire } from 'node:module'
const require = createRequire('/usr/lib/node_modules/openclaw/package.json')
const { chromium } = require('playwright-core')
const origin = process.env.ORIGIN, key = process.env.KEY, out = process.env.OUT ?? '/tmp'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const fail = (message) => { console.error('FAIL', message); process.exitCode = 1 }
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', (error) => errors.push(String(error)))
await page.goto(`${origin}/__preview/login?key=${key}`)
const version = await page.evaluate(async () => (await fetch('/api/version')).json())
console.log('version', JSON.stringify(version))
await page.goto(`${origin}/admin?tab=update`)
await page.getByTestId('current-version').waitFor()
console.log('status before', await page.getByTestId('update-status').textContent())
await page.getByRole('button', { name: '立即检查' }).click()
await page.waitForFunction(() => !document.querySelector('[data-testid="update-status"]')?.textContent?.includes('尚未检查'), null, { timeout: 30000 }).catch(() => undefined)
await page.waitForTimeout(1500)
const status = await page.getByTestId('update-status').textContent()
const command = await page.getByTestId('upgrade-command').textContent()
const body = await page.locator('body').innerText()
console.log('status', status)
console.log('command', command)
console.log('latest line', body.split('\n').find((line) => line.startsWith('最新')) ?? '-')
if (status !== '有新版本可用') fail(`expected 有新版本可用, got ${status}`)
if (command !== 'docker compose pull && docker compose up -d') fail(`unexpected command ${command}`)
await page.screenshot({ path: `${out}/rhea190-m13-admin-update.png`, fullPage: true })
const report = await page.evaluate(async () => (await fetch('/api/admin/update')).json())
console.log('report', JSON.stringify(report.check))
await page.goto(`${origin}/admin`)
const notice = page.getByRole('status', { name: '新版本提示' })
await notice.waitFor({ timeout: 10000 }).catch(() => fail('admin notice missing'))
console.log('admin notice', (await notice.textContent())?.replace(/\s+/g, ' '))
await page.goto(`${origin}/settings`)
const settingsNotice = page.getByRole('status', { name: '新版本提示' })
await settingsNotice.waitFor({ timeout: 10000 }).catch(() => fail('settings notice missing'))
await page.screenshot({ path: `${out}/rhea190-m13-settings.png` })
console.log('settings notice', (await settingsNotice.textContent())?.replace(/\s+/g, ' '))
const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
const phone = await mobile.newPage()
await phone.goto(`${origin}/__preview/login?key=${key}`)
await phone.goto(`${origin}/admin?tab=update`)
await phone.getByTestId('upgrade-command').waitFor()
const overflow = await phone.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)
console.log('mobile horizontal overflow px', overflow)
if (overflow > 0) fail('mobile overflow')
await phone.screenshot({ path: `${out}/rhea190-m13-mobile.png`, fullPage: true })
if (errors.length) fail(`page errors: ${errors.join('; ')}`)
await browser.close()
console.log(process.exitCode ? 'RESULT FAIL' : 'RESULT PASS')
